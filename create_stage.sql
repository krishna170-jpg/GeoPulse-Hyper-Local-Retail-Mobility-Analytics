-- GeoPulse - Member 3: CSV file format and upload stage
USE SCHEMA GEOPULSE_DB.RAW;

CREATE OR REPLACE FILE FORMAT CSV_GPS_FORMAT
  TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = ('', 'NULL')
  TIMESTAMP_FORMAT = 'YYYY-MM-DD HH24:MI:SS'
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE OR REPLACE STAGE GPS_STAGE FILE_FORMAT = CSV_GPS_FORMAT;

SHOW FILE FORMATS;
SHOW STAGES;
